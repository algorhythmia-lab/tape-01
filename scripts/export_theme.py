#!/usr/bin/env python3
"""Generate native colors from the shared, source-exportable brand token snapshot."""
import argparse
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--check", action="store_true")
args = parser.parse_args()
tokens = json.loads((ROOT / "docs/design-tokens.json").read_text())["colors"]
paths = {"obsidian": ("substrate", "obsidian_void"), "basalt": ("substrate", "basalt_surface"),
         "raised": ("substrate", "carbon_raised"), "border": ("substrate", "graphite_border"),
         "slate": ("substrate", "forensic_slate"), "pure": ("neutrals", "pure_bone"),
         "red": ("telemetry", "akira_red"),
         "bone": ("neutrals", "bone_chalk"), "muted": ("neutrals", "titanium_mist"),
         "amber": ("telemetry", "bebop_amber"), "green": ("telemetry", "phosphor_green"),
         "cyan": ("telemetry", "optic_cyan")}
header = "#pragma once\n\n#include <cstdint>\n\n// Generated by scripts/export_theme.py from docs/design-tokens.json.\nnamespace sys01::theme {\n"
for name, (group, key) in paths.items():
    value = tokens[group][key]["hex"].removeprefix("#").lower()
    assert len(value) == 6 and all(c in "0123456789abcdef" for c in value)
    header += f"inline constexpr std::uint32_t {name} = 0xff{value};\n"
header += "} // namespace sys01::theme\n"
output = ROOT / "apps/desktop/Theme.hpp"
if args.check:
    if output.read_text() != header:
        raise SystemExit("Native theme is stale: run scripts/export_theme.py")
else:
    output.write_text(header)
# Verify actual normal-text contrast against every native text background.
def luminance(hex_value):
    rgb = [int(hex_value[i:i + 2], 16) / 255 for i in (1, 3, 5)]
    linear = [v / 12.92 if v <= 0.04045 else ((v + 0.055) / 1.055) ** 2.4 for v in rgb]
    return sum(v * weight for v, weight in zip(linear, (0.2126, 0.7152, 0.0722)))
for text_name in ("bone", "muted"):
    tg, tk = paths[text_name]
    foreground = luminance(tokens[tg][tk]["hex"])
    for background_name in ("obsidian", "basalt"):
        bg, bk = paths[background_name]
        background = luminance(tokens[bg][bk]["hex"])
        assert (foreground + 0.05) / (background + 0.05) >= 4.5, (text_name, background_name)
print("native theme matches brand snapshot; normal label contrast >= 4.5:1")
